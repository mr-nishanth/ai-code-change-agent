"""Delivery port: what a publisher is asked to do and what it reports back.

A publisher receives only verified, immutable inputs: the exact base commit, the file changes taken
from the hashed patch artifact and the tree hashes the result must have. It never receives a
workspace, a path on the platform host, a URL from a Story or any text written by a model.
"""

import uuid
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from typing import Protocol

from ai_code_change_agent.application.workspaces.models import FileChange


class DeliveryOutcome(StrEnum):
    """What a publisher reports. Gate D values are kept unchanged for compatibility; Gate D.1 adds
    explicit values for the hosted pull request flow."""

    DELIVERY_DISABLED = "DELIVERY_DISABLED"  # nothing was done
    LOCAL_BRANCH_DELIVERED = "LOCAL_BRANCH_DELIVERED"  # a branch in a local bare repository
    PR_CREATED = "PR_CREATED"  # Gate D placeholder: no adapter returns it; never accepted
    FAILED = "FAILED"  # Gate D failure value (local publisher and read-only boundary)
    # Gate D.1 (hosted provider pull request publisher)
    GITHUB_BRANCH_PUBLISHED = "GITHUB_BRANCH_PUBLISHED"  # progress only: branch exists, no PR yet
    PULL_REQUEST_CREATED = "PULL_REQUEST_CREATED"  # confirmed by a re-read of the pull request
    DELIVERY_FAILED = "DELIVERY_FAILED"
    DELIVERY_OUTCOME_UNKNOWN = "DELIVERY_OUTCOME_UNKNOWN"  # a write may or may not have happened


FAILURE_OUTCOMES = frozenset(
    {
        DeliveryOutcome.FAILED,
        DeliveryOutcome.DELIVERY_FAILED,
        DeliveryOutcome.DELIVERY_OUTCOME_UNKNOWN,
        DeliveryOutcome.GITHUB_BRANCH_PUBLISHED,  # a branch without a pull request is not success
    }
)


@dataclass(frozen=True)
class DeliveryTarget:
    """The registered repository, read from the registry by the platform (never from a caller)."""

    repository_id: uuid.UUID
    git_provider: str
    provider_repository_id: str
    owner: str
    name: str
    default_branch: str


@dataclass(frozen=True)
class BaselineEntry:
    """One file of the pinned Gate C snapshot (repository-relative, already validated)."""

    path: str
    executable: bool
    sha256: str


@dataclass(frozen=True)
class PullRequestSpec:
    """Title and body generated by the platform from verified artifacts only (no model prose, no
    Story text). Pull requests are drafts unless an owner decision says otherwise."""

    title: str
    body: str
    draft: bool = True


@dataclass(frozen=True)
class DeliveryStep:
    """One remote step a publisher performed or reconciled; stored as non-secret evidence."""

    name: str  # e.g. "ref", "pull_request"
    status: str  # "CREATED", "REUSED", "UNKNOWN"
    value: str | None = None  # a SHA or a pull request number, never a credential


@dataclass(frozen=True)
class DeliveryRequest:
    target: DeliveryTarget
    base_commit_sha: str
    baseline_tree_hash: str
    result_tree_hash: str
    branch: str
    changes: tuple[FileChange, ...]
    commit_message: str
    commit_time: datetime
    manifest_sha256: str
    baseline: tuple[BaselineEntry, ...] = ()  # the pinned snapshot, for remote baseline checks
    pull_request: PullRequestSpec | None = None  # only for pull request publishers


@dataclass(frozen=True)
class DeliveryReceipt:
    outcome: DeliveryOutcome
    branch: str | None = None
    commit_sha: str | None = None
    tree_hash: str | None = None  # platform tree hash re-computed from the commit that now exists
    created: bool = False  # False when an identical delivery already existed
    pr_id: str | None = None
    pr_url: str | None = None
    failure_code: str | None = None
    pr_number: int | None = None
    pr_head_sha: str | None = None
    base_branch: str | None = None
    progress: tuple[DeliveryStep, ...] = ()


class DeliveryPublisher(Protocol):
    async def publish(self, request: DeliveryRequest) -> DeliveryReceipt: ...


class DeliveryPublishers:
    """Maps the registry's git_provider key to its publisher. A missing key is an error: there is
    never a fallback to another provider."""

    def __init__(self, publishers: dict[str, DeliveryPublisher] | None = None) -> None:
        self._publishers = dict(publishers or {})

    def register(self, key: str, publisher: DeliveryPublisher) -> None:
        self._publishers[key] = publisher

    def get(self, key: str) -> DeliveryPublisher | None:
        return self._publishers.get(key)

    @property
    def keys(self) -> tuple[str, ...]:
        return tuple(sorted(self._publishers))
