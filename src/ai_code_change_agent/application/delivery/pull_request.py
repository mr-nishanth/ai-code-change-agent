"""Draft pull request text, generated from verified records only (no model prose, no Story text
beyond the validated issue key)."""

import re

from ai_code_change_agent.application.artifacts.redaction import find_secrets
from ai_code_change_agent.application.delivery.errors import DeliveryError
from ai_code_change_agent.application.delivery.manifest import DeliveryManifest
from ai_code_change_agent.application.git_providers.delivery import PullRequestSpec
from ai_code_change_agent.validation.schemas import ValidationReport

_KEY = re.compile(r"[A-Z][A-Z0-9_]{1,31}-[0-9]{1,10}")
_SAFE = re.compile(r"[A-Za-z0-9._/:@-]{1,300}")
MAX_BODY = 60_000


def safe(value: str) -> str:
    return value if _SAFE.fullmatch(value) else "(withheld: unsupported characters)"


def pull_request_title(issue_key: str) -> str:
    if not _KEY.fullmatch(issue_key):
        raise DeliveryError("pr_text_rejected")
    return f"[{issue_key}] AI Code Change Agent change"


def build_pull_request(
    manifest: DeliveryManifest, report: ValidationReport, *, draft: bool = True
) -> PullRequestSpec:
    if not report.passed:
        raise DeliveryError("validation_not_passed")
    rows = [
        ("Jira issue", manifest.issue_key),
        ("Attempt", manifest.attempt_id),
        ("Base commit", manifest.base_commit_sha),
        ("Plan SHA-256", manifest.plan_sha256),
        ("Changeset SHA-256", manifest.changeset_sha256),
        ("Validation report SHA-256", manifest.validation_report_sha256),
    ]
    lines = ["## AI Code Change Agent", "", "| Field | Value |", "|---|---|"]
    lines += [f"| {k} | {safe(v)} |" for k, v in rows]
    lines += ["", "### Changed files", ""]
    lines += [f"- `{safe(f.path)}` ({f.operation})" for f in report.changed_files[:200]]
    lines += ["", "### Independent validation", "", "| Check | Result |", "|---|---|"]
    lines += [f"| {c.kind.value} | {c.status.value} |" for c in report.checks]
    lines += [f"| command {safe(c.command_id)} | {c.status} |" for c in report.commands]
    lines += [
        "",
        "### Notes",
        "",
        "- Generated by an AI coding agent inside an isolated, network-less sandbox.",
        "- Validated independently by the platform; the PLAN and FINAL gates were decided by "
        "the configured approval mode (automatic policy or an unverified operator).",
        "- This pull request is a draft and is never merged automatically.",
    ]
    body = "\n".join(lines)
    if len(body) > MAX_BODY or find_secrets(body):
        raise DeliveryError("pr_text_rejected")
    return PullRequestSpec(pull_request_title(manifest.issue_key), body, draft=draft)
